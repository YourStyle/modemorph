-- Счётчик включённого в подписку — отдельно от бесплатных лимитов.
--
-- ЗАЧЕМ. Подписчик проходил мимо тарификации целиком: _is_subscriber() отвечал
-- «можно, осталось 999» и на этом всё. Примерка стоит 14,10 ₽ (две генерации),
-- а годовой тариф — 2 990 ₽, то есть 249 ₽ в месяц, и на нём сидят пятеро из
-- восьми активных подписчиков. Восемнадцать примерок в месяц — и подписка
-- уходит в минус.
--
-- Это не теория. Профиль 1554 (годовой): апрель 2026 — 43 примерки и 5 фото,
-- 621 ₽ себестоимости против 249 ₽ выручки. И так в шести месяцах из двенадцати.
--
-- ПОЧЕМУ ОТДЕЛЬНАЯ ТАБЛИЦА, а не limits. limits хранит бесплатный тариф. Если
-- писать туда же остаток подписчика, при истечении подписки человек унесёт с
-- собой большое число — ровно та поломка, из-за которой из reconcile убрали
-- запись 999 («churned subscribers kept unlimited access»). Два счётчика в двух
-- таблицах не могут перепутаться.
--
-- ПОЧЕМУ НЕ usage_events. Это журнал аналитики: его пишет best-effort хелпер,
-- который глотает исключения, и его можно проредить при чистке. Мера, по
-- которой решают, списывать ли с человека деньги, не может зависеть от того,
-- удалась ли запись в аналитику.
--
-- СБРОС ЛЕНИВЫЙ, без крона: период хранится строкой, и первое же обращение
-- после истечения месяца обнуляет счётчик. Крон, который «должен» ходить раз в
-- месяц по всем профилям, — это ещё одна вещь, которая молча не сработает.

CREATE TABLE IF NOT EXISTS subscription_usage (
    user_profile_id   BIGINT      NOT NULL REFERENCES user_profiles (id) ON DELETE CASCADE,
    feature           TEXT        NOT NULL,
    used              INTEGER     NOT NULL DEFAULT 0,
    period_started_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    PRIMARY KEY (user_profile_id, feature)
);

-- Годовому тарифу — потолки шире месячного, иначе апгрейд бессмысленный.
--
-- После 042 monthly и yearly имели ОДИНАКОВЫЕ месячные потолки (35/8/300).
-- Месячному подписчику, упёршемуся в 35 фото, было некуда идти: годовой давал
-- ровно столько же в месяц и отличался только ценой. Тариф, который дороже, но
-- не больше, — не тариф, а скидка за предоплату.
--
-- Куда расширять, решает себестоимость, а не симметрия:
--
--   примерка 14,10 ₽   8 штук = 113 ₽ из 233 ₽ месячного бюджета
--   фото      3,10 ₽   35 штук = 109 ₽
--   стилист   0,04 ₽   300 штук = 12 ₽
--
-- Примерка вчетверо дороже фото, поэтому щедрость там мгновенно съедает весь
-- запас: 12 примерок вместо 8 стоили бы столько же, сколько всё остальное
-- вместе, и фото пришлось бы урезать — то есть «апгрейд» отнял бы главное.
-- Расширяем по дешёвым осям, примерку двигаем на +2.
--
--   годовой:  50 фото / 10 примерок / 600 стилиста  (было 35 / 8 / 300)
--             +43% оцифровок, +25% примерок, вдвое больше стилиста
--
-- Худший случай (человек выбирает всё): 3 893,33 ₽ из 6 990 ₽ — маржа 44,3%
-- против 66,6% у месячного. Ниже она у годового по построению: 6 990 / 12 =
-- 582 ₽ в месяц против 699 ₽, то есть тариф на 17% дешевле и при этом обязан
-- давать больше. 44% — цена того, чтобы у апгрейда был смысл; по медианному
-- расходу (6 фото в месяц) реальная маржа около 90%.
--
-- Посев переписан ЦЕЛИКОМ, а не одним UPDATE на изменившиеся строки: тест
-- test_plan_limits читает потолки из последней миграции, где есть INSERT INTO
-- plan_limits, и полное объявление не даёт ему отстать от прода.


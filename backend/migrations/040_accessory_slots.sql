-- Бэкфилл канонических слагов для аксессуаров, которые пользователи принесли
-- ДО того, как у аксессуаров появился слот в образе.
--
-- Зачем. Семь семей (сумка, головной убор, шарф, ремень, очки, часы,
-- украшения) до сих пор объявлялись бесслотовыми: детектор их пропускал,
-- clothing_taxonomy.is_accessory() возвращал True, генератор образов выбрасывал.
-- Люди приносили их всё равно — 122 вещи у 44 пользователей — и 149 раз клали
-- в образ руками через чекбоксы. Слот теперь есть; без этого бэкфилла он не
-- увидит ни одну из уже принесённых вещей, и фича выйдет пустой ровно для тех,
-- кто её и просил действием.
--
-- Что трогаем. Только строки, где clothing_type НЕ несёт типа: NULL, пустая
-- строка, 'аксессуар' (значение по умолчанию = «никто не заполнил»), 'верхняя'
-- (то же самое, но из старой формы).
--
-- ВАЖНО про порядок. В backend/clothing_taxonomy.py правила упорядочены и
-- первое совпадение выигрывает: правило платья стоит ВЫШЕ правила ремня,
-- поэтому «Платье с поясом» остаётся платьем. Здесь тот же порядок даёт
-- CASE (ветки проверяются сверху вниз), а первая ветка — защита: если имя
-- называет настоящую вещь, строку не трогаем вовсе.
--
-- Один UPDATE, а не семь: регулярка-защита нужна каждой ветке, и в семи
-- отдельных UPDATE её пришлось бы скопировать семь раз.

UPDATE wardrobe_user_items SET clothing_type = CASE
    -- Защита: имя называет настоящую вещь → не трогаем (NULL = нет ветки).
    WHEN names._n ~ '(плать|юбк|брюк|джинс|шорт|футболк|рубашк|блуз|топ |майк|лонгслив|водолазк|свитер|джемпер|пуловер|кофт|кардиган|худи|свитшот|толстовк|жилет|безрукавк|пиджак|блейзер|жакет|пальто|куртк|пуховик|парк|шуб|дублёнк|дубленк|комбинезон|костюм|комплект|туфл|ботинк|кроссовк|кед|сапог|босоножк|сандал|dress|skirt|pants|jeans|shorts|shirt|blouse|sweater|hoodie|jacket|coat|shoes|boots|sneakers)'
        THEN clothing_type
    WHEN names._n ~ '(сумк|клатч|шоппер|рюкзак|bag|backpack|tote)'          THEN 'bag'
    WHEN names._n ~ '(шапк|кепк|бейсболк|панам|шляп|берет|cap|hat|beanie)'  THEN 'hat'
    WHEN names._n ~ '(шарф|платок|снуд|scarf)'                             THEN 'scarf'
    WHEN names._n ~ '(ремен|пояс|belt)'                                     THEN 'belt'
    WHEN names._n ~ '(очки|оправ|солнцезащ|sunglass|eyewear)'               THEN 'sunglasses'
    WHEN names._n ~ '(часы|наручн|watch)'                                   THEN 'watch'
    WHEN names._n ~ '(ожерель|серьг|серёж|брасл|кольцо|цепочк|подвеск|колье|кулон|брошь|чокер|necklace|earring|bracelet|jewel)'
        THEN 'jewellery'
    ELSE clothing_type
END
FROM (SELECT id AS _id,
             lower(coalesce(item_name, '') || ' ' || coalesce(item_name_en, '')) AS _n
      FROM wardrobe_user_items) AS names
WHERE wardrobe_user_items.id = names._id
  AND (clothing_type IS NULL OR clothing_type IN ('', 'аксессуар', 'верхняя'));

-- Легаси-значения, которые до сих пор лежали в UNSET_VALUES и теперь являются
-- настоящими типами. TYPE_ALIASES их и так резолвит на чтении — приводим и в БД,
-- чтобы фильтры по самой колонке видели то же самое.
UPDATE wardrobe_user_items SET clothing_type = 'watch' WHERE clothing_type = 'часы';
UPDATE wardrobe_user_items SET clothing_type = 'hat' WHERE clothing_type = 'головной убор';

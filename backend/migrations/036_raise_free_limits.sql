-- Бесплатный тариф поднят до варианта A (решение владельца 24.08.2026).
--   фото 3→5, стилист 3→25, идеи 10→100, образы 3→25, примерка 1→2
--
-- Новым профилям это выдаёт backend/app/api/me.py. Существующим — эта миграция,
-- иначе правка коснулась бы только будущих, а их приходит около восьми в месяц:
-- 299 человек, которые уже здесь, не увидели бы ничего.
--
-- Почему щедро к тексту: просмотр идеи, сохранение образа и запрос к стилисту
-- стоят 4 копейки. Прежние 10 идей экономили 40 копеек — за эту сумму продукт
-- покупал у человека ощущение, что ему всё время отказывают. Картинки подняты
-- умеренно, потому что на них приходится 96% стоимости бесплатного тарифа.
--
-- GREATEST, а не присваивание: у кого-то лимит уже выше нового значения —
-- админ выдал, подписка разблокировала. Прямой UPDATE ОТОБРАЛ БЫ у них разницу,
-- и это выглядело бы как поломка, а не как щедрость. Планка только поднимается.
--
-- Стоимость, если КАЖДЫЙ израсходует всё до нуля: 5 619 ₽ (фото 1 897,
-- примерка 2 115, текст 1 608). Реально будет кратно меньше — из 455 аккаунтов
-- 160 не заполнили даже профиль, а лимиты исчерпали единицы: фото 10 человек,
-- идеи 11, примерку 2, стилиста ни один.

UPDATE limits
   SET wardrobe_items_anlyzed = GREATEST(wardrobe_items_anlyzed,   5),
       ai_requests            = GREATEST(ai_requests,             25),
       ideas_viewed           = GREATEST(ideas_viewed,           100),
       outfits_saved          = GREATEST(outfits_saved,           25),
       vton_used              = GREATEST(vton_used,                2);

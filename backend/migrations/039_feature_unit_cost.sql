-- Себестоимость функции в рублях — рядом с её ценой в кредитах.
--
-- До сих пор она жила в комментариях к миграциям и в моей голове: 2,90 ₽ за
-- фото, 14,10 ₽ за примерку. Человек, который открывает раздел «Тарификация»,
-- видел только цену в кредитах и не мог ответить на единственный вопрос,
-- ради которого туда заходят: сколько это приносит.
--
-- Числа замерены 22.08 на 15 реальных вещах и одной живой примерке:
--   оцифровка  2,90 ₽ — одна генерация выкладки сеткой 2×2 на lite-модели
--   примерка  14,10 ₽ — ДВЕ генерации на дорогой: пасс 1 одежда, пасс 2 лицо
--   текст      0,04 ₽ — идея, образ, запрос к стилисту
--
-- Колонка редактируемая: при смене модели цена меняется, и обновлять её
-- деплоем ради одного числа — способ гарантировать, что её не обновят. Пустое
-- значение допустимо и означает «не замеряли»: интерфейс тогда честно скажет,
-- что маржу посчитать не из чего, вместо того чтобы показать ноль.

ALTER TABLE feature_costs
  ADD COLUMN IF NOT EXISTS unit_cost_rub NUMERIC(10, 2);

UPDATE feature_costs SET unit_cost_rub = 2.90  WHERE feature_name = 'wardrobe_items_anlyzed';
UPDATE feature_costs SET unit_cost_rub = 14.10 WHERE feature_name = 'vton_used';
UPDATE feature_costs SET unit_cost_rub = 0.04  WHERE feature_name IN ('ai_requests', 'ideas_viewed', 'outfits_saved');

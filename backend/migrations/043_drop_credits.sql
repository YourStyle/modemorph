-- Кредитные таблицы уходят. Отдельным файлом от 042 намеренно: та миграция
-- гасит остатки и переводит людей на планы, эта — сносит опустевшее. Если между
-- ними что-то пойдёт не так, откатывать придётся только вторую.
--
-- Что остаётся жить: credit_transactions. Это единственная запись о том, кому и
-- сколько было выдано и что именно обменяли на месяц подписки (reason =
-- 'plan_migration'). Снести её значило бы удалить доказательство собственной же
-- конвертации. Таблица становится архивом: код в неё больше не пишет — после
-- этой миграции в ней нет ни одного живого писателя, — но читать её можно.

-- ── Бесплатный тариф больше не персональная копия лимитов ──────────────────
--
-- limits хранил остаток на каждого зарегистрировавшегося. Из-за этого смена
-- бесплатного тарифа не доставалась тем, кто уже зарегистрирован: миграция 036
-- подняла лимиты, а 302 существующих профиля остались со старыми, и понадобился
-- отдельный UPDATE. Теперь тариф — это строки в plan_limits, общие для всех.
-- Потраченное перенесено в subscription_usage миграцией 042.
--
-- reconcile_limits() снимается первой: она принимает тип строки limits, поэтому
-- таблица без неё не удаляется. CASCADE тут не годится — он снёс бы всё, что
-- зависит, не показав что именно.
DROP FUNCTION IF EXISTS public.reconcile_limits(bigint);
DROP TABLE IF EXISTS limits;

-- ── Кредиты ────────────────────────────────────────────────────────────────
DROP TABLE IF EXISTS credit_packs;
DROP TABLE IF EXISTS user_credits;

-- Функции, которые начисляли кредиты. add_credits вызывался из кода, которого
-- больше нет; вторая висела на активации подписки и дарила 40 кредитов.
DROP FUNCTION IF EXISTS public.add_credits(integer, integer, text, text);
DROP FUNCTION IF EXISTS public.grant_subscription_credits(integer);

-- ── Колонки, ставшие враньём ───────────────────────────────────────────────
--
-- cost_credits — цена функции в кредитах. Ровно она десять месяцев не совпадала
-- с ключами приложения и молча делала любую функцию стоящей один кредит.
-- unit_cost_rub рядом остаётся: себестоимость никуда не делась, она и есть то,
-- ради чего этот экран открывают.
ALTER TABLE feature_costs      DROP COLUMN IF EXISTS cost_credits;
ALTER TABLE feature_costs      DROP COLUMN IF EXISTS cost_subscription_credits;
ALTER TABLE subscription_pricing DROP COLUMN IF EXISTS credits;
ALTER TABLE user_subscriptions   DROP COLUMN IF EXISTS credits_included;


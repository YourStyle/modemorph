-- Настоящие шорты, сохранённые как 'sporty-pants'.
--
-- TEMP_RANGES даёт sporty-pants окно (5, 25), а shorts — (20, 35). Из-за этого
-- «шорты до колена» предлагались в образах при +19 °C. Вещь названа шортами,
-- типизирована спортивными брюками — это ошибка данных, а не фильтра.
--
-- Только wardrobe_user_items. Каталог намеренно не трогаем: там «шорт» в имени
-- при другом типе почти всегда означает не шорты —
--   45 строк с clothing_type='skirt'  = «Мини юбка-шорты», «Юбка-шорты со складками»
--   28 строк с clothing_type='classic' = «Костюм из топа и шорт», «Комплект из футболки и шорт»
-- то есть там тип как раз верный, и переписывать его значило бы ломать данные.
--
-- Те же исключения применены и здесь на случай, если пользователь завёл юбку-шорты
-- или костюм с шортами. Идемпотентно: строки, уже помеченные 'shorts', не трогаются.

UPDATE wardrobe_user_items
SET clothing_type = 'shorts'
WHERE clothing_type = 'sporty-pants'
  AND item_name ILIKE '%шорт%'
  AND item_name NOT ILIKE '%юбка-шорт%'
  AND item_name NOT ILIKE '%юбка шорт%'
  AND item_name NOT ILIKE '%костюм%'
  AND item_name NOT ILIKE '%комплект%'
  AND item_name NOT ILIKE '%комбинезон%';

-- Заглушки объектов Supabase, чтобы миграции проигрывались с нуля.
--
-- Три ранние миграции (000, 001, 004) написаны во времена Supabase и
-- рассчитывают на схему auth, которую создавал он сам:
--   auth.users   — таблица, на неё ссылается внешний ключ в 004_item_dislikes;
--   auth.uid()   — кто сейчас в сессии, используется в политиках RLS;
--   auth.jwt()   — разбор токена, там же.
-- Без них накат с чистой базы падает на четвёртой миграции.
--
-- Почему заглушки, а не правка самих миграций. На проде после переезда на свой
-- Postgres схема auth осталась ПУСТОЙ, а внешних ключей на неё нет ни одного —
-- при миграции данных их сняли. То есть боевая схема и результат проигрывания
-- истории уже не совпадают, и это нормально: миграции описывают путь, а не
-- итог. Переписать их задним числом значило бы развести прод и репозиторий ещё
-- сильнее, причём молча — применённые файлы повторно не выполняются.
--
-- Файл НАМЕРЕННО лежит вне backend/migrations: оттуда scripts/migrate.sh
-- накатывает на прод всё подряд, и заглушка поехала бы туда же.

CREATE SCHEMA IF NOT EXISTS auth;

-- Только то, на что ссылается внешний ключ. Остальные колонки Supabase тестам
-- не нужны, а перечислять их значит притворяться, что мы воспроизводим Supabase.
CREATE TABLE IF NOT EXISTS auth.users (
    id UUID PRIMARY KEY
);

-- Возвращают NULL: политики RLS в тестах не проверяются (приложение ходит в базу
-- под своей ролью и разграничивает доступ само, см. get_current_user). Функции
-- нужны лишь для того, чтобы CREATE POLICY распарсился.
CREATE OR REPLACE FUNCTION auth.uid() RETURNS UUID
    LANGUAGE sql STABLE AS $$ SELECT NULL::uuid $$;

CREATE OR REPLACE FUNCTION auth.jwt() RETURNS JSONB
    LANGUAGE sql STABLE AS $$ SELECT '{}'::jsonb $$;
